import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'public', 'THIRD_PARTY_NOTICES.txt');
const excludedPlatforms = /^@smartspectra\/node-sdk-(linux|win32)-/;
const licenseFile = /^(licen[cs]e|copying|notice)([.-].*)?$/i;
const rule = '='.repeat(78);
const bundledLicenseTexts = { 'node_modules/@mediapipe/tasks-vision': { license: 'Apache-2.0', file: 'public/tracking/LICENSE-2.0.txt' } };

function read(file) {
  return readFileSync(file, 'utf8').replace(/\r\n?/g, '\n').replace(/[ \t]+$/gm, '').trimEnd();
}

function licenseOf(pkg) {
  if (typeof pkg.license === 'string') return pkg.license;
  if (pkg.license && typeof pkg.license.type === 'string') return pkg.license.type;
  if (Array.isArray(pkg.licenses)) return pkg.licenses.map(item => item.type).filter(Boolean).join(' OR ');
  return '';
}

function productionPackages(problems) {
  const lock = JSON.parse(readFileSync(path.join(root, 'package-lock.json'), 'utf8'));
  const result = [];
  for (const [key, entry] of Object.entries(lock.packages)) {
    if (!key.startsWith('node_modules/') || entry.dev === true) continue;
    const dir = path.join(root, key);
    const name = key.slice(key.lastIndexOf('node_modules/') + 'node_modules/'.length);
    if (excludedPlatforms.test(name)) continue;
    if (!existsSync(path.join(dir, 'package.json'))) { problems.push(`${key}: not installed; run npm ci`); continue; }
    const pkg = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8'));
    const license = licenseOf(pkg);
    const files = readdirSync(dir, { withFileTypes: true }).filter(item => item.isFile() && licenseFile.test(item.name)).map(item => item.name).sort();
    if (!license) problems.push(`${key}: no license field`);
    const bundled = bundledLicenseTexts[key];
    if (!files.length && !(bundled && bundled.license === license)) problems.push(`${key}: no license file`);
    const texts = files.length ? files.map(file => [file, read(path.join(dir, file))]) : [[`${license} text: see ${bundled.file} above`, '']];
    result.push({ key, name, version: pkg.version, license, texts });
  }
  return result.sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
}

function render(problems) {
  const out = ['Idlewild third-party notices', '', 'Generated by scripts/third-party-notices.mjs. Do not edit by hand.', ''];
  out.push(rule, 'BUNDLED ASSETS', rule, '');
  for (const [title, file] of [
    ['Model provenance (public/models/ATTRIBUTION.md)', 'public/models/ATTRIBUTION.md'],
    ['Local tracking assets (public/tracking/ATTRIBUTION.md)', 'public/tracking/ATTRIBUTION.md'],
    ['Apache License 2.0 (public/tracking/LICENSE-2.0.txt)', 'public/tracking/LICENSE-2.0.txt'],
  ]) {
    if (!existsSync(path.join(root, file))) { problems.push(`${file}: missing`); continue; }
    out.push(`--- ${title} ---`, '', read(path.join(root, file)), '');
  }
  out.push(rule, 'ELECTRON AND CHROMIUM RUNTIME', rule, '',
    'The desktop app embeds the Electron runtime (MIT) and Chromium. Packaged builds ship Electron\'s license as',
    'Contents/Resources/LICENSE.electron.txt and the Chromium third-party licenses as',
    'Contents/Resources/LICENSES.chromium.html inside Idlewild.app.', '');
  const electronLicense = path.join(root, 'node_modules', 'electron', 'LICENSE');
  if (existsSync(electronLicense)) out.push(`--- Electron ${JSON.parse(readFileSync(path.join(root, 'node_modules', 'electron', 'package.json'), 'utf8')).version} (MIT) ---`, '', read(electronLicense), '');
  else problems.push('node_modules/electron/LICENSE: missing');
  out.push(rule, 'SMARTSPECTRA SDK (OPTIONAL, PROPRIETARY)', rule, '',
    'The @smartspectra/node-sdk packages are proprietary software of Presage Technologies, distributed under',
    "Presage's Terms of Service: https://presagetech.com/legal/terms-of-service",
    'Their own license, NOTICE, LGPL, FFmpeg and third-party notice files ship inside the application at',
    'node_modules/@smartspectra/node-sdk*/ and are reproduced below where they are license files.', '');
  out.push(rule, 'PRODUCTION DEPENDENCIES', rule, '');
  const packages = productionPackages(problems);
  for (const item of packages) out.push(`${item.key}@${item.version} (${item.license || 'UNKNOWN'})`);
  out.push('');
  for (const item of packages) {
    out.push(rule, `${item.name}@${item.version}`, `License: ${item.license || 'UNKNOWN'}`, rule, '');
    for (const [file, text] of item.texts) out.push(`--- ${file} ---`, '', text, '');
  }
  return out.join('\n').replace(/\n+$/, '\n');
}

const problems = [];
const text = render(problems);
if (problems.length) {
  console.error(`Notices incomplete:\n${problems.join('\n')}`);
  process.exit(1);
}
if (process.argv.includes('--check')) {
  if (!existsSync(output) || readFileSync(output, 'utf8') !== text) {
    console.error('public/THIRD_PARTY_NOTICES.txt is missing or stale; run npm run notices.');
    process.exit(1);
  }
  console.log('Third-party notices are current.');
} else {
  writeFileSync(output, text);
  console.log(`Wrote ${path.relative(root, output)}`);
}
